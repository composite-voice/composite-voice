/**
 * Tests for the AWS event-stream codec and CRC32 implementation.
 *
 * Fixture bytes were generated with an independent reference encoder using
 * Node's zlib CRC32, so they validate the framing layout (prelude, header
 * encoding, CRC placement) against a second implementation — not just
 * against our own round-trip.
 */

// jsdom does not provide TextEncoder/TextDecoder — install Node's implementations.
import { TextEncoder, TextDecoder } from 'util';
global.TextEncoder = TextEncoder as unknown as typeof global.TextEncoder;
global.TextDecoder = TextDecoder as unknown as typeof global.TextDecoder;

import { crc32 } from '../../../../src/utils/aws/crc32';
import {
  encodeEventStreamMessage,
  decodeEventStreamMessage,
} from '../../../../src/utils/aws/eventstream';

