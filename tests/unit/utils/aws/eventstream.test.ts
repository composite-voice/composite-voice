describe('crc32', () => {
  it('should produce the standard check value for "123456789"', () => {
    expect(crc32(new TextEncoder().encode('123456789'))).toBe(0xcbf43926);
  });

  it('should match known values', () => {
    expect(crc32(new Uint8Array(0))).toBe(0);
    expect(crc32(new TextEncoder().encode('hello'))).toBe(0x3610a686);
  });

  it('should support incremental computation', () => {
    const whole = crc32(new TextEncoder().encode('123456789'));
    const partial = crc32(
      new TextEncoder().encode('456789'),
      crc32(new TextEncoder().encode('123'))
    );
    expect(partial).toBe(whole);
  });
});

describe('encodeEventStreamMessage', () => {
  it('should produce byte-identical AudioEvent frames to the reference encoder', () => {
    const frame = encodeEventStreamMessage(
      {
        ':message-type': 'event',
        ':event-type': 'AudioEvent',
        ':content-type': 'application/octet-stream',
      },
      new Uint8Array([1, 2, 3, 4])
    );

    expect(Array.from(frame)).toEqual(Array.from(AUDIO_EVENT_FIXTURE));
  });

  it('should produce byte-identical TranscriptEvent frames to the reference encoder', () => {
    const frame = encodeEventStreamMessage(
      {
        ':message-type': 'event',
        ':event-type': 'TranscriptEvent',
        ':content-type': 'application/json',
      },
      new TextEncoder().encode('{"Transcript":{"Results":[]}}')
    );

    expect(Array.from(frame)).toEqual(Array.from(TRANSCRIPT_EVENT_FIXTURE));
  });

  it('should encode empty payloads (end-of-stream AudioEvent)', () => {
    const frame = encodeEventStreamMessage({ ':event-type': 'AudioEvent' }, new Uint8Array(0));
    const decoded = decodeEventStreamMessage(frame);

    expect(decoded.payload.length).toBe(0);
    expect(decoded.headers[':event-type']).toBe('AudioEvent');
  });

  it('should reject oversized header names and values', () => {
    expect(() => encodeEventStreamMessage({ ['x'.repeat(256)]: 'v' }, new Uint8Array(0))).toThrow(
      'header name too long'
    );
    expect(() =>
      encodeEventStreamMessage({ name: 'v'.repeat(0x10000) }, new Uint8Array(0))
    ).toThrow('header value too long');
  });
});

describe('decodeEventStreamMessage', () => {
  it('should decode the AudioEvent fixture', () => {
    const message = decodeEventStreamMessage(AUDIO_EVENT_FIXTURE);

    expect(message.headers).toEqual({
      ':message-type': 'event',
      ':event-type': 'AudioEvent',
      ':content-type': 'application/octet-stream',
    });
    expect(Array.from(message.payload)).toEqual([1, 2, 3, 4]);
  });

  it('should decode from an ArrayBuffer (WebSocket binary frame)', () => {
    const buffer = TRANSCRIPT_EVENT_FIXTURE.slice().buffer;
    const message = decodeEventStreamMessage(buffer);

    expect(message.headers[':event-type']).toBe('TranscriptEvent');
    expect(JSON.parse(new TextDecoder().decode(message.payload))).toEqual({
      Transcript: { Results: [] },
    });
  });

  it('should round-trip encode/decode with a binary payload', () => {
    const payload = new Uint8Array(1024);
    for (let i = 0; i < payload.length; i++) payload[i] = i % 251;

    const headers = {
      ':message-type': 'event',
      ':event-type': 'AudioEvent',
      ':content-type': 'application/octet-stream',
    };
    const decoded = decodeEventStreamMessage(encodeEventStreamMessage(headers, payload));

    expect(decoded.headers).toEqual(headers);
    expect(Array.from(decoded.payload)).toEqual(Array.from(payload));
  });

  it('should reject frames with a corrupted prelude CRC', () => {
    const corrupted = AUDIO_EVENT_FIXTURE.slice();
    corrupted[9] = (corrupted[9] as number) ^ 0xff;
    expect(() => decodeEventStreamMessage(corrupted)).toThrow('prelude CRC mismatch');
  });

  it('should reject frames with a corrupted message CRC', () => {
    const corrupted = AUDIO_EVENT_FIXTURE.slice();
    // Flip a payload byte — prelude stays valid but the message CRC fails.
    corrupted[corrupted.length - 5] = (corrupted[corrupted.length - 5] as number) ^ 0xff;
    expect(() => decodeEventStreamMessage(corrupted)).toThrow('message CRC mismatch');
  });

  it('should reject truncated frames and length mismatches', () => {
    expect(() => decodeEventStreamMessage(new Uint8Array(4))).toThrow('too short');
    expect(() => decodeEventStreamMessage(AUDIO_EVENT_FIXTURE.subarray(0, 50))).toThrow(
      'length mismatch'
    );
  });

  it('should decode non-string header value types', () => {
    // Hand-built frame with one of each: boolean true, int32, and a string.
    const headerBytes: number[] = [];
    const pushName = (name: string): void => {
      headerBytes.push(name.length, ...Array.from(new TextEncoder().encode(name)));
    };
    pushName('bool');
    headerBytes.push(0); // type 0 = boolean true, no value bytes
    pushName('int');
    headerBytes.push(4, 0, 0, 1, 44); // type 4 = int32, value 300
    pushName('str');
    headerBytes.push(7, 0, 2, 104, 105); // type 7 = string, "hi"

    const totalLength = 12 + headerBytes.length + 4;
    const frame = new Uint8Array(totalLength);
    const view = new DataView(frame.buffer);
    view.setUint32(0, totalLength, false);
    view.setUint32(4, headerBytes.length, false);
    view.setUint32(8, crc32(frame.subarray(0, 8)), false);
    frame.set(headerBytes, 12);
    view.setUint32(totalLength - 4, crc32(frame.subarray(0, totalLength - 4)), false);

    const message = decodeEventStreamMessage(frame);
    expect(message.headers['bool']).toBe(true);
    expect(message.headers['int']).toBe(300);
    expect(message.headers['str']).toBe('hi');
    expect(message.payload.length).toBe(0);
  });

  it('should reject unknown header value types', () => {
    const headerBytes = [1, 120, 42]; // name "x", bogus type 42
    const totalLength = 12 + headerBytes.length + 4;
    const frame = new Uint8Array(totalLength);
    const view = new DataView(frame.buffer);
    view.setUint32(0, totalLength, false);
    view.setUint32(4, headerBytes.length, false);
    view.setUint32(8, crc32(frame.subarray(0, 8)), false);
    frame.set(headerBytes, 12);
    view.setUint32(totalLength - 4, crc32(frame.subarray(0, totalLength - 4)), false);

    expect(() => decodeEventStreamMessage(frame)).toThrow('Unknown event-stream header value type');
  });
});
